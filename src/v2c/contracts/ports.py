"""Consumer-owned execution ports, independent of concrete HTTP clients."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Protocol

from .runner import (
    AuthorizeReply,
    CommandRequest,
    CommandResult,
    PrepareReply,
    PrepareRequest,
    VMAllocation,
)
from .workflow import ExecutionLimits, PendingExecution, RunClaim, RunRecord


class RunnerPort(Protocol):
    @property
    def is_test(self) -> bool: ...

    async def prepare(self, request: PrepareRequest) -> PrepareReply: ...
    async def authorize(
        self, workspace_id: str, attempt_id: str, generation: int
    ) -> AuthorizeReply: ...
    async def execute(self, request: CommandRequest) -> CommandResult: ...
    async def status(self, command_id: str) -> CommandResult: ...
    async def cancel(self, command_id: str) -> CommandResult: ...
    async def checkpoint(self, workspace_id: str) -> bytes: ...


class VMProviderPort(Protocol):
    async def create(self, allocation_id: str, purpose: str) -> VMAllocation: ...
    async def status(self, vm_id: str) -> VMAllocation: ...
    async def destroy(self, vm_id: str) -> VMAllocation: ...


RunnerFactory = Callable[["VMAllocation"], RunnerPort]


class PipelineSettings(Protocol):
    @property
    def command_timeout_seconds(self) -> int: ...
    @property
    def provision_timeout_seconds(self) -> int: ...
    @property
    def provision_poll_seconds(self) -> float: ...
    @property
    def run_timeout_seconds(self) -> int: ...
    @property
    def model_max_input_bytes(self) -> int: ...
    @property
    def work_root(self) -> Path: ...
    @property
    def execution_limits(self) -> ExecutionLimits: ...


class CleanupPort(Protocol):
    def allocation(self, attempt_id: str) -> VMAllocation | None: ...
    async def destroy(self, claim: RunClaim, allocation: VMAllocation) -> None: ...
    async def cancel_run(self, run_id: str) -> bool: ...


class ImportSettings(Protocol):
    @property
    def work_root(self) -> Path: ...
    @property
    def max_upload_bytes(self) -> int: ...


class PipelineRuntime(Protocol):
    async def execute(self, claim: RunClaim) -> RunRecord | PendingExecution: ...
    async def cancel_run(self, run_id: str) -> bool: ...
    async def reconcile(self, claim: RunClaim) -> bool: ...
